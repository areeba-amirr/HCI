export const REPORT_TEXT: Record<ReportLang, ReportText> = { en, ur };

const UR_MONTHS = ["جنوری", "فروری", "مارچ", "اپریل", "مئی", "جون", "جولائی", "اگست", "ستمبر", "اکتوبر", "نومبر", "دسمبر"];
const UR_DAYS = ["اتوار", "پیر", "منگل", "بدھ", "جمعرات", "جمعہ", "ہفتہ"];

type DateStyle = "day" | "dayLong" | "date" | "dateLong" | "dateTime" | "dateTimeLong" | "short";
const EN_FORMATS: Record<DateStyle, string> = {
  day: "EEEE d MMM yyyy",
  dayLong: "EEEE d MMMM yyyy",
  date: "d MMM yyyy",
  dateLong: "d MMMM yyyy",
  dateTime: "d MMM yyyy, HH:mm",
  dateTimeLong: "d MMMM yyyy, HH:mm",
  short: "d MMM",
};

/** Dates in the report language. Urdu uses Urdu month and day names with Western digits. */
export function reportDate(d: Date, style: DateStyle, lang: ReportLang) {
  if (lang === "en") return format(d, EN_FORMATS[style]);
  const date = `${d.getDate()} ${UR_MONTHS[d.getMonth()]}${style === "short" ? "" : ` ${d.getFullYear()}`}`;
  const time = format(d, "HH:mm");
  switch (style) {
    case "day":
    case "dayLong":
      return `${UR_DAYS[d.getDay()]}، ${date}`;
    case "dateTime":
    case "dateTimeLong":
      return `${date}، ${time}`;
    default:
      return date;
  }
}
